"""Unified experiment status from registry.yaml + completed results.json files.

Usage:
  python collect_results.py            # human-readable console table
  python collect_results.py --md       # markdown results table (ledger block) to stdout
  python collect_results.py --md FILE  # ...write it to FILE instead

The --md output is the AUTHORITATIVE per-experiment P/R/F1 table: it is read
straight from the cluster's results.json files, so it overrides any hand-written
summary on a discrepancy. It is the source of the paper's ledger appendix.
"""

import argparse
import sys
import json
from datetime import date
from pathlib import Path

import yaml

AUTO_START = "<!-- AUTO-RESULTS:START -->"
AUTO_END = "<!-- AUTO-RESULTS:END -->"


def load_results(outputs="outputs"):
    """Return (completed: {exp_id: results}, bad: [(name, err)])."""
    completed, bad = {}, []
    for p in sorted(Path(outputs).glob("e*/results.json")):
        try:
            with open(p) as f:
                r = json.load(f)
        except (json.JSONDecodeError, OSError) as e:
            # empty / truncated / half-written results.json (crashed job) — skip, don't die
            bad.append((p.parent.name, f"{type(e).__name__}: {e}"))
            continue
        completed[r["experiment_id"]] = r
    return completed, bad


def _best_epoch_scores(history: dict, st: str):
    """Best dev epoch's tuned P/R/F1 + threshold for subtask st."""
    best = None
    for ep in history.values():
        blk = ep["dev"].get(st)
        if not blk or "tuned" not in blk:
            return None
        if best is None or blk["tuned"]["f1"] > best[0]["f1"]:
            best = (blk["tuned"], blk.get("best_threshold", float("nan")))
    return best


def _test_scores(r: dict, st: str):
    """Test P/R/F1 dict for subtask st, whichever key the run wrote."""
    blk = r.get("test", {}).get(st, {})
    for key in ("tuned", "viterbi", "thr0.5"):
        if key in blk and "f1" in blk[key]:
            return blk[key]
    return None


def _expnum(exp_id):
    """Sort key: e7 < e12 (numeric, not lexicographic)."""
    try:
        return int(exp_id[1:])
    except ValueError:
        return 10**9


def iter_rows(completed):
    """Yield one row per (exp, subtask):
    (exp_id, subtask, test_dict|None, test_f1|None, dev_pr|None, dev_f1, thr|None).
    dev_f1 comes from the stored best_dev_f1 (always present); dev_pr from the best
    epoch's tuned block (may be None); thr from the stored best_threshold map."""
    for exp_id in sorted(completed, key=_expnum):
        r = completed[exp_id]
        test_f1_map = r.get("best_test_f1", {})
        thr_map = r.get("best_threshold", {})
        for st, dev_f1 in r["best_dev_f1"].items():
            dev = _best_epoch_scores(r.get("history", {}), st)
            thr = thr_map.get(st, dev[1] if dev else None)
            yield (exp_id, st, _test_scores(r, st), test_f1_map.get(st),
                   dev[0] if dev else None, dev_f1, thr)


def _pct(x):
    return f"{x*100:.2f}" if x is not None else "-"


def render_markdown(completed):
    """The authoritative per-experiment P/R/F1 table, wrapped in AUTO markers.
    ASCII-only so it survives Windows `>` redirects and the local splice."""
    lines = [
        AUTO_START,
        f"*Auto-generated by `collect_results.py --md` on {date.today().isoformat()} "
        f"from the cluster `results.json` -- do not hand-edit this block "
        f"-- regenerate it instead.*",
        "",
        "| Exp | Subtask | Test P | Test R | Test F1 | Dev F1 @ thr |",
        "|-----|---------|-------:|-------:|--------:|-------------:|",
    ]
    for exp, st, test, test_f1, dev_pr, dev_f1, thr in iter_rows(completed):
        tp = _pct(test["precision"]) if test else "-"
        tr = _pct(test["recall"]) if test else "-"
        tf = f"{test_f1:.4f}" if test_f1 is not None else "-"
        # thr < 0 is the CRF/Viterbi sentinel (no threshold) -> omit
        devcell = f"{dev_f1:.4f} @{thr:.2f}" if thr is not None and thr >= 0 else f"{dev_f1:.4f}"
        lines.append(f"| {exp} | {st} | {tp} | {tr} | {tf} | {devcell} |")
    lines.append(AUTO_END)
    return "\n".join(lines) + "\n"


def print_console(completed, bad):
    if bad:
        print(f"\n[!] {len(bad)} unreadable results.json (empty or corrupt) - excluded:")
        for name, err in bad:
            print(f"  {name}: {err}")
    if not completed:
        print("No results yet. Check outputs/e*/results.json after training completes.")
        return
    registry = {}
    rp = Path("registry.yaml")
    if rp.exists():
        registry = yaml.safe_load(open(rp)).get("experiments", {})

    def pr(s):
        return f"{s['precision']*100:>6.2f} {s['recall']*100:>6.2f}" if s else f"{'-':>6} {'-':>6}"

    header = (f"{'Exp':<12} {'Subtask':<11} {'DevP':>6} {'DevR':>6} {'DevF1':>7} {'thr':>5} "
              f"{'TestP':>6} {'TestR':>6} {'TestF1':>7}  Description")
    print("\n" + header)
    print("-" * len(header))
    for exp, st, test, test_f1, dev_pr, dev_f1, thr in iter_rows(completed):
        desc = registry.get(exp, {}).get("description", "")
        tf = f"{test_f1:>7.4f}" if test_f1 is not None else f"{'-':>7}"
        thr_s = f"{thr:>5.2f}" if thr is not None else f"{'-':>5}"
        print(f"{exp:<12} {st:<11} {pr(dev_pr)} {dev_f1:>7.4f} {thr_s} {pr(test)} {tf}  {desc}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--md", nargs="?", const="-", metavar="FILE",
                    help="emit the markdown results block (to FILE, or stdout if bare)")
    args = ap.parse_args()

    completed, bad = load_results()
    if args.md is not None:
        md = render_markdown(completed)
        if args.md == "-":
            print(md, end="")
        else:
            Path(args.md).write_text(md, encoding="utf-8")
            print(f"Wrote {sum(1 for _ in iter_rows(completed))} rows -> {args.md}", file=sys.stderr)
        if bad:  # to stderr so a `--md > file` redirect keeps the markdown clean
            print(f"[!] skipped {len(bad)} empty/corrupt: {', '.join(n for n, _ in bad)}", file=sys.stderr)
    else:
        print_console(completed, bad)


if __name__ == "__main__":
    main()
